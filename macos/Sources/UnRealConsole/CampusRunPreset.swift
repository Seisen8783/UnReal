import Foundation

/// 校园跑一键预设。
///
/// 站在操场边刷脸的时候不方便现调参数，而这套设置每一条都是实测出来的：
/// 偏移值来自 `tools/fence_check.py` 的围栏预检，配速来自「两条证据链要自洽」的推理。
/// 所以打成一包，一键套用。
struct CampusRunPreset {
    /// 标定偏移（米）：把内置轨迹挪到**实测可达区**的中心。
    ///
    /// 数值来自 `tools/fence_check.py` 的实测对比：
    /// 偏移前围栏最小余量 0.38 m、北侧几乎贴边；偏移后 11.96 m，
    /// 且原本 244 个超出实测可达区的点全部回到区内。
    /// 跑道形状与每圈长度（906 m）完全不变——只是整条轨迹平移了一下。
    static let eastMeters = -17.2
    static let northMeters = -11.5

    /// 回放配速（分:秒 每公里）。默认 7'00"，落在「正常跑步」区间的中段。
    ///
    /// 判定链的分工是：**桩只验有没有撞库，速度和数据看手机**。
    /// 所以桩链给的是「有没有刷过、刷了几段」，手机链给的是距离、配速、时长。
    /// 于是配速有两个约束：
    /// 1. 不能慢于走路（< 9'00"/公里 会被判无效），也不能快到非人类（< 4'00"/公里 ≈ 15 km/h）；
    /// 2. `公里数 ÷ 配速` 要约等于你真实跑完这段距离的耗时——
    ///    这样桩链的时间跨度和手机上报的时长才对得上。
    /// 按「实际耗时 ÷ 公里数」算出来最稳：走 3 km 花 20 分钟 → 6'40"，
    /// 手机显示的是「3 km / 20 分 / 9 km/h」，两头都像真的。
    static let pace = "7:00"

    /// 目标公里数。桩计多少就填多少，两边对得上最省心。
    ///
    /// 手机链的数字就是成绩数据，这个值直接决定上报的距离。
    static let kilometers = "1.50"

    /// 流程步骤：撞库与回放是并行的，不是先后。
    static let steps: [(title: String, detail: String)] = [
        ("小程序点「开始跑步」，走到操场边的起点打卡桩",
         "桩是闸门：它只验你有没有撞库，通过了服务器才开始记你这一趟"),
        ("在桩前刷脸（撞库）",
         "没撞库，后面刷出来的数据服务端不认"),
        ("控制台点「接管定位权限」→「开始回放」",
         "速度和数据看手机，所以手机链必须全程在跑；手机也要一直留在操场上，"
         + "离开围栏会被标「非校园区域」"),
        ("沿路每个桩前都刷一次，终点桩再刷一次",
         "桩链决定这一趟记几段；漏刷一个桩就少一段记录"),
        ("手机侧的数字才算成绩：距离和配速按这次的目标填",
         "桩只管验人，报给服务器的里程与配速取自手机上报的轨迹")
    ]

    /// 操作禁忌：中途断了，前面的撞库就白做。
    static let cautions: [String] = [
        "回放途中不要暂停、不要拔线——上报出现空洞，前面的撞库就白做了",
        "配速按「实际耗时 ÷ 公里数」算：既落在正常跑步区间，"
        + "又让桩链的时间跨度和手机上报的时长对得上",
        "配速低于 9'00\"（走路）可能判无效，高于 4'00\"（15 km/h 以上）会显示成非人类"
    ]
}
